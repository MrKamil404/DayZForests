//! Tłumaczenia interfejsu: PL (źródłowy) / EN / DE.
//!
//! Słownik kluczowany POLSKIM tekstem źródłowym — brak wpisu oznacza
//! powrót do tekstu polskiego, więc interfejs zawsze działa.

use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Lang {
    Pl,
    En,
    De,
}

impl Lang {
    pub const ALL: [Lang; 3] = [Lang::Pl, Lang::En, Lang::De];
    pub fn name(&self) -> &'static str {
        match self {
            Lang::Pl => "Polski",
            Lang::En => "English",
            Lang::De => "Deutsch",
        }
    }
    pub fn code(&self) -> &'static str {
        match self {
            Lang::Pl => "pl",
            Lang::En => "en",
            Lang::De => "de",
        }
    }
    pub fn from_code(s: &str) -> Option<Lang> {
        match s.to_lowercase().as_str() {
            "pl" => Some(Lang::Pl),
            "en" => Some(Lang::En),
            "de" => Some(Lang::De),
            _ => None,
        }
    }
}

/// Preferencje UI (język + skróty klawiszowe) — zapisywane obok presetów.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct UiPrefs {
    #[serde(default)]
    pub language: String,
    /// Skróty użytkownika: (nazwa akcji, skrót "Ctrl+O" / None = wyłączony).
    #[serde(default)]
    pub shortcuts: Vec<(String, Option<String>)>,
}

impl Default for UiPrefs {
    fn default() -> Self {
        Self { language: "pl".into(), shortcuts: Vec::new() }
    }
}

pub const PREFS_FILE: &str = "ui_settings.json";

impl UiPrefs {
    pub fn load(path: impl AsRef<std::path::Path>) -> Self {
        std::fs::read_to_string(path)
            .ok()
            .and_then(|s| serde_json::from_str::<UiPrefs>(&s).ok())
            .and_then(|p| {
                // walidacja kodu języka
                Lang::from_code(&p.language)?;
                Some(p)
            })
            .unwrap_or_default()
    }
    pub fn save(&self, path: impl AsRef<std::path::Path>) {
        if let Ok(json) = serde_json::to_string_pretty(self) {
            let _ = std::fs::write(path, json);
        }
    }
}

